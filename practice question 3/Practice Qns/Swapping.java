public class Swapping 
{
 public static void main(String [] arg)  
 {
    int a=10;
    int b= 20;
    int c;
    System.out.println("Before Swapping");
    System.out.println("value of a :"+a);
    System.out.println("value of b :"+b);
    c=a;
    a=b;
    b=c;
    System.out.println("After Swapping");
    System.out.println("value of a :"+a);
    System.out.println("value of b :"+b);
 } 
}
